package transferbench

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// BisectionOptions describes a half-to-half concurrent transfer test.
type BisectionOptions struct {
	NumGPUs  int  // total GPUs; must be even and >= 2
	SubExecs int  // CUs (GFX) or DMA queues per Transfer
	DMA      bool // copy with DMA engines instead of GPU kernels
	Bidir    bool // also send upper half -> lower half at the same time
}

// BisectionConfig returns a TransferBench config file for a bisection test.
//
// Pairwise tests (the p2p preset, nvbandwidth) move one pair at a time, which
// never fills a switch uplink, so they cannot show whether a PCIe fabric is
// non-blocking. This config runs two tests: one pair alone as the baseline,
// then every GPU in the lower half sending to its partner in the upper half at
// once. On a non-blocking fabric the per-Transfer bandwidth of the second test
// stays close to the baseline; a drop means a shared link somewhere.
//
// TransferBench has no preset for this (its a2a preset is all-to-all), so it is
// generated here. Each config line is one test; Transfers on a line run
// concurrently. Lines starting with ## are echoed into the output.
func BisectionConfig(o BisectionOptions) (string, error) {
	if o.NumGPUs < 2 || o.NumGPUs%2 != 0 {
		return "", fmt.Errorf("bisection needs an even number of GPUs (got %d)", o.NumGPUs)
	}
	if o.SubExecs < 1 {
		return "", fmt.Errorf("sub-execs must be at least 1 (got %d)", o.SubExecs)
	}
	half := o.NumGPUs / 2
	exe := "G"
	if o.DMA {
		exe = "D"
	}
	// The source GPU executes and writes into the peer's memory, matching the
	// p2p preset's default (USE_REMOTE_READ=0).
	xfer := func(src, dst int) string {
		return fmt.Sprintf("(G%d->%s%d->G%d)", src, exe, src, dst)
	}

	var pairs []string
	for i := 0; i < half; i++ {
		pairs = append(pairs, xfer(i, i+half))
		if o.Bidir {
			pairs = append(pairs, xfer(i+half, i))
		}
	}
	base := []string{xfer(0, half)}
	if o.Bidir {
		base = append(base, xfer(half, 0))
	}

	dir := "->"
	if o.Bidir {
		dir = "<->"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by ai-studio-cli transferbench bisection\n")
	fmt.Fprintf(&b, "## Baseline: GPU 0 %s GPU %d alone\n", dir, half)
	fmt.Fprintf(&b, "%d %d %s\n", len(base), o.SubExecs, strings.Join(base, " "))
	fmt.Fprintf(&b, "## Bisection: GPUs 0-%d %s GPUs %d-%d, all at once. Compare per-Transfer GB/s with the baseline.\n",
		half-1, dir, half, o.NumGPUs-1)
	fmt.Fprintf(&b, "%d %d %s\n", len(pairs), o.SubExecs, strings.Join(pairs, " "))
	return b.String(), nil
}

// DetectGPUs counts the GPUs the ROCm kernel driver exposes: KFD topology
// nodes with SIMDs (CPU nodes have none). Partitioned GPUs (DPX/CPX) count
// once per partition, which is also how TransferBench numbers them.
// root is "/" in production and a fake tree in tests.
func DetectGPUs(root string) (int, error) {
	pattern := filepath.Join(root, "sys", "class", "kfd", "kfd", "topology", "nodes", "*", "properties")
	files, err := filepath.Glob(pattern)
	if err != nil {
		return 0, err
	}
	if len(files) == 0 {
		return 0, fmt.Errorf("no KFD topology found — is the amdgpu driver loaded? (looked for %s)", pattern)
	}
	n := 0
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return 0, err
		}
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) == 2 && fields[0] == "simd_count" {
				if v, err := strconv.Atoi(fields[1]); err == nil && v > 0 {
					n++
				}
				break
			}
		}
	}
	return n, nil
}
